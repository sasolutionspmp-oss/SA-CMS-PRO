import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';

// Actual synthetic-site UI acceptance. Only this script's newly created estimate
// is changed; existing rate, assembly, source and HTTP acceptance records are read.
const manifest = JSON.parse(await readFile(process.env.CIPHER_RUNTIME_MANIFEST || '/tmp/cipher-r0-runtime/fixture.secret.json', 'utf8'));
const acceptance = JSON.parse(await readFile(new URL('../../docs/framework/evidence/r1/est01-http-acceptance.json', import.meta.url), 'utf8'));
const base = process.env.CIPHER_RUNTIME_URL || 'http://127.0.0.1:18880';
const output = new URL(process.env.CIPHER_CAPTURE_DIR || '../test-results/connected-estimating/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CIPHER_CHROME || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
let stage = 'sign in'; let createdId;
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const browserErrors = []; const consoleErrors = []; const unexpectedHttp = []; const expectedAuth = [];
  let authenticated = false;
  page.on('pageerror', error => browserErrors.push(error.message));
  page.on('console', message => { if (authenticated && message.type() === 'error') consoleErrors.push({ message: message.text(), source: message.location().url }); });
  page.on('response', response => { if (response.status() >= 400) { const path = new URL(response.url()).pathname; const value = { path, status: response.status() }; if (!authenticated && path.endsWith('cipher_aec.api.v1.session') && response.status() === 401) expectedAuth.push(value); else unexpectedHttp.push(value); } });
  page.on('dialog', dialog => dialog.accept());
  const route = `/projects/${encodeURIComponent(manifest.project)}/estimates`;
  await page.goto(`${base}${route}`);
  await expect(page.getByRole('heading', { name: 'Sign in to your workspace', exact: true })).toBeVisible();
  await page.getByLabel('Email or username', { exact: true }).fill(manifest.users.primary.user);
  await page.getByLabel('Password', { exact: true }).fill(manifest.users.primary.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Estimates', exact: true })).toBeVisible();
  authenticated = true;
  const read = async (kind, id) => {
    const params = new URLSearchParams({ company: manifest.company, project: manifest.project, kind, record_id: id });
    const response = await page.request.get(`${base}/api/method/cipher_aec.estimating.api.get_record?${params}`);
    if (!response.ok()) throw new Error(`Scoped ${kind} read failed.`);
    return (await response.json()).message.data;
  };
  stage = 'existing qualified source metadata';
  const [source, assembly, originalEstimate] = await Promise.all([read('rate', acceptance.records.rate), read('assembly', acceptance.records.assembly), read('estimate', acceptance.records.estimate)]);
  await page.screenshot({ path: new URL('connected-estimate-register.png', output).pathname, fullPage: true });
  stage = 'new estimate draft';
  await page.getByRole('button', { name: 'New estimate', exact: true }).click();
  const create = page.locator('ui5-dialog[header-text="Create estimate draft"]');
  const title = `Synthetic UI estimate ${crypto.randomUUID().slice(0, 8)}`;
  await create.getByRole('textbox', { name: 'Estimate title', exact: true }).fill(title);
  await create.getByRole('textbox', { name: 'Estimate currency', exact: true }).fill(originalEstimate.currency);
  await create.getByRole('textbox', { name: 'Estimate pricing date', exact: true }).fill(originalEstimate.pricing_date);
  await create.getByRole('button', { name: 'Create draft', exact: true }).click();
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible();
  createdId = new URL(page.url()).pathname.split('/').pop();
  if (!createdId || createdId === acceptance.records.estimate) throw new Error('A separate estimate was not created.');
  const detailUrl = `${base}${route}/${createdId}`;
  stage = 'atomic authored row paste';
  await page.getByRole('button', { name: 'Paste rows', exact: true }).click();
  const paste = page.locator('ui5-dialog[header-text="Paste estimate rows"]');
  await paste.getByRole('textbox', { name: 'Tab-separated estimate rows', exact: true }).fill(`Synthetic manual direct quantity\t10\t${source.rate.unit_id}\t${source.id}\tUI-DIRECT\t0\nSynthetic manual assembly quantity\t1\t${assembly.assembly.basis_unit_id}\t${assembly.id}\tUI-ASSEMBLY\t0`);
  await paste.getByRole('button', { name: 'Add pasted rows', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Line 2 quantity', exact: true })).toHaveValue('1');
  await page.getByRole('textbox', { name: 'Estimate basis', exact: true }).fill('Explicit synthetic UI acceptance. Quantities are manually authored against existing qualified immutable rate and assembly revisions.');
  const save = async () => {
    const response = page.waitForResponse(value => new URL(value.url()).pathname.endsWith('cipher_aec.estimating.api.calculate_revision') && value.request().method() === 'POST');
    await page.getByRole('button', { name: 'Calculate & save revision', exact: true }).first().click();
    const result = await response;
    if (!result.ok()) throw new Error('Server calculation failed.');
    const body = result.request().postDataJSON();
    if (result.request().headers()['idempotency-key'] !== body.operation_id) throw new Error('Operation key mismatch.');
    return { receipt: (await result.json()).message.data, request: body };
  };
  stage = 'first exact server calculation';
  const first = await save();
  await expect(page.getByRole('note', { name: /Revision 1 saved/ })).toBeVisible();
  if (first.request.expected_revision !== null || first.request.lines[0].quantity.amount !== '10') throw new Error('First calculation inputs differ.');
  stage = 'keyboard successor calculation';
  await page.getByRole('textbox', { name: 'Line 1 quantity', exact: true }).fill('11');
  await page.getByRole('textbox', { name: 'Line 1 description', exact: true }).press('Tab');
  await expect(page.getByRole('textbox', { name: 'Line 1 quantity', exact: true })).toBeFocused();
  const second = await save();
  await expect(page.getByRole('note', { name: /Revision 2 saved/ })).toBeVisible();
  if (second.request.expected_revision !== first.receipt.revision.id || second.request.lines[0].line_id !== first.request.lines[0].line_id || second.request.lines[1].line_id !== first.request.lines[1].line_id) throw new Error('Successor source or stable row identity changed.');
  stage = 'persisted immutable readback';
  const [head, oldSnapshot, newSnapshot] = await Promise.all([read('estimate', createdId), read('snapshot', first.receipt.calculation.id), read('snapshot', second.receipt.calculation.id)]);
  if (head.current_revision !== second.receipt.revision.id || head.revision_number !== 2 || oldSnapshot.inputs.lines[0].quantity.amount !== '10' || newSnapshot.inputs.lines[0].quantity.amount !== '11') throw new Error('Persisted revision readback differs.');
  await page.goto(detailUrl);
  await expect(page.getByRole('textbox', { name: 'Line 1 quantity', exact: true })).toHaveValue('11');
  const table = page.locator('ui5-table[accessible-name="Editable estimate lines"]');
  const aligned = async () => {
    const headers = table.getByRole('columnheader'); const cells = table.getByRole('row').nth(1).getByRole('gridcell');
    await expect(headers).toHaveCount(7); await expect(cells).toHaveCount(7);
    await expect.poll(async () => Math.max(...await Promise.all((await headers.all()).map(async (header, index) => { const a = await header.boundingBox(); const b = await cells.nth(index).boundingBox(); return !a || !b ? 999 : Math.max(Math.abs(a.x - b.x), Math.abs(a.width - b.width)); })))).toBeLessThanOrEqual(2);
  };
  await aligned();
  await page.screenshot({ path: new URL('connected-estimate-editor-desktop.png', output).pathname, fullPage: true });
  stage = 'rate and cited source inspection';
  await page.getByRole('button', { name: 'Inspect line 1 source', exact: true }).click();
  const sourceDialog = page.locator('ui5-dialog[header-text="Rate source"]');
  await expect(sourceDialog).toContainText(source.rate.quote_reference);
  await page.screenshot({ path: new URL('connected-estimate-rate-source.png', output).pathname, fullPage: true });
  await sourceDialog.getByRole('link', { name: source.source_citations[0].document_title, exact: true }).first().click();
  await expect(page.locator('ui5-dialog[header-text="Estimate source text"] .source-text')).toBeVisible();
  await page.screenshot({ path: new URL('connected-estimate-source-page.png', output).pathname, fullPage: true });
  await page.getByRole('button', { name: 'Close source text', exact: true }).click();
  await page.getByRole('button', { name: 'Close source details', exact: true }).click();
  stage = 'assembly inspection';
  await page.getByRole('button', { name: 'Inspect line 2 source', exact: true }).click();
  await expect(page.locator('ui5-dialog[header-text="Assembly revision"]')).toContainText(assembly.assembly.title);
  await page.screenshot({ path: new URL('connected-estimate-assembly-source.png', output).pathname, fullPage: true });
  await page.getByRole('button', { name: 'Close source details', exact: true }).click();
  stage = 'saved revision comparison';
  await page.getByRole('tab', { name: 'Revision comparison', exact: true }).click();
  await page.getByRole('button', { name: 'Compare with predecessor', exact: true }).click();
  await expect(page.locator('ui5-table[accessible-name="Estimate revision comparison"]')).toContainText('Changed');
  await page.screenshot({ path: new URL('connected-estimate-revision-comparison.png', output).pathname, fullPage: true });
  stage = 'snapshot inspection';
  await page.getByRole('tab', { name: 'Saved calculation', exact: true }).click();
  await page.getByRole('button', { name: 'Inspect calculation snapshot', exact: true }).click();
  await expect(page.locator('ui5-dialog[header-text="Calculation snapshot"]')).toContainText(second.receipt.calculation.output_digest);
  await page.screenshot({ path: new URL('connected-estimate-snapshot.png', output).pathname, fullPage: true });
  await page.getByRole('button', { name: 'Close source details', exact: true }).click();
  for (const [width, label] of [[900, 'tablet'], [390, 'phone']]) {
    stage = `${label} numeric layout`;
    await page.setViewportSize({ width, height: 1000 }); await page.goto(detailUrl);
    await expect(page.getByRole('textbox', { name: 'Line 1 quantity', exact: true })).toHaveValue('11');
    await aligned();
    if (!(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))) throw new Error('Viewport overflow.');
    await page.screenshot({ path: new URL(`connected-estimate-editor-${label}.png`, output).pathname, fullPage: true });
    await page.getByRole('textbox', { name: 'Line 1 quantity', exact: true }).focus();
    await expect(page.getByRole('textbox', { name: 'Line 1 quantity', exact: true })).toBeFocused();
    await page.screenshot({ path: new URL(`connected-estimate-numeric-focus-${label}.png`, output).pathname, fullPage: true });
  }
  if (browserErrors.length || consoleErrors.length || unexpectedHttp.length) throw new Error('Unexpected browser/console/network errors.');
  await writeFile(new URL('verification.json', output), JSON.stringify({ mode: 'actual-frappe-estimating-ui', captured_at: new Date().toISOString(), mocked_requests: false, business_writes: true, created_estimate: createdId, original_acceptance_estimate_unchanged: acceptance.records.estimate, source_rate: source.id, source_assembly: assembly.id, revisions: [first.receipt.revision.id, second.receipt.revision.id], snapshots: [first.receipt.calculation.id, second.receipt.calculation.id], operation_ids: [first.request.operation_id, second.request.operation_id], totals: [first.receipt.calculation.result.total, second.receipt.calculation.result.total], manual_quantities_preserved: ['10', '11'], stable_line_ids_preserved: true, viewports: [1440, 900, 390], keyboard_quantity_focus: true, column_alignment_tolerance_px: 2, expected_initial_authentication_responses: expectedAuth, browser_errors: browserErrors, console_errors: consoleErrors, unexpected_http_errors: unexpectedHttp, qualified_takeoff: false, baseline_acceptance: false, live_model: false }, null, 2));
  console.log('Actual estimating UI journey passed: own persisted draft, two exact revisions, source/snapshot inspection, comparison and all three widths. No credentials logged.');
} catch {
  console.error(`Actual estimating UI verification failed at ${stage}. No credentials or authentication errors were logged. Created estimate: ${createdId || 'none'}.`); process.exitCode = 1;
} finally { await browser.close(); }
