"""Read and draft boundary for Ricky's HTTP tools.

The standalone SDK remains a synthetic automation harness. This adapter exposes
only reviewed read and draft tools and never requests or applies approvals. It
does not provide session identity or replace the practice console's action API;
those remain pre-pilot work. Responses are marked presentation views with
provenance pointing to the unchanged receipt in the underlying SDK catalog.
"""
from __future__ import annotations

import copy
from typing import Any

from .core.ids import hash_json
from .ricky_sdk import CATALOG, CATALOG_BY_NAME, CATALOG_HASH, RickySDK, catalog as sdk_catalog

CATALOG_VERSION = "ricky-served/1.0.0"
# Adding an SDK tool never exposes it here automatically. A new served tool
# needs an explicit review of its handler as well as its declared side effects.
SERVED_TOOLS = frozenset({
    "read_brief", "read_project_state", "read_document", "preview", "draft_change", "draft_supplier_bill", "get_status",
    "read_supplier_invoices", "record_supplier_invoice", "compute_invoice_match", "draft_supplier_credit_note",
    "draft_bill_correction", "read_customer_terms", "read_customer_deposits", "draft_deposit_application",
    "draft_credit_memo", "draft_write_off", "read_budget_versions", "draft_budget_revision", "record_forecast_snapshot",
    "read_forecast_snapshots", "read_identities", "read_release_rules", "preview_release", "read_contracts",
    "register_contract_agreement", "prepare_contract_signature", "record_insurance_certificate",
})

if not SERVED_TOOLS <= set(CATALOG_BY_NAME) or any(
    CATALOG_BY_NAME[name].side_effects not in ("none", "draft") for name in SERVED_TOOLS
):
    raise RuntimeError("the served Ricky allowlist must contain only existing read and draft tools")


class ServedRickyRefused(PermissionError):
    """A tool or generic SDK call is outside Ricky's served read and draft scope."""

    code = "ricky_read_draft_only"


def _tool_description(spec: Any) -> dict[str, Any]:
    description = spec.describe()
    schema = description.pop("receipt_schema")
    schema["description"] = "Served presentation view; generated instructions address a person. The provenance identifies the immutable SDK receipt, not a hash of this view."
    original = schema["properties"]
    hashes = {name: original.pop(name) for name in ("catalog_hash", "prev_hash", "receipt_hash")}
    schema["required"] = [name for name in schema["required"] if name not in hashes] + ["presentation", "receipt_provenance"]
    original["presentation"] = {
        "type": "object", "required": ["version", "catalog_hash", "raw_receipt"],
        "properties": {"version": {"type": "string", "enum": [CATALOG_VERSION]},
                       "catalog_hash": hashes["catalog_hash"], "raw_receipt": {"type": "boolean", "enum": [False]}},
        "additionalProperties": False,
    }
    original["receipt_provenance"] = {
        "type": "object", "required": ["id", "receipt_hash", "catalog_hash"],
        "properties": {"id": copy.deepcopy(original["id"]), "receipt_hash": hashes["receipt_hash"], "catalog_hash": hashes["catalog_hash"]},
        "additionalProperties": False,
    }
    description["response_schema"] = schema
    return description


def catalog() -> dict[str, Any]:
    """Describe preparation routes without advertising any human action as executable."""
    tools = [_tool_description(spec) for spec in CATALOG if spec.name in SERVED_TOOLS]
    operations = []
    for route in sdk_catalog()["operations"]:
        preparation = [name for name in route["tools"] if name in SERVED_TOOLS]
        operations.append({
            "operation": route["operation"], "class": "read_draft" if preparation else "human_only",
            "reachable": False, "tools": preparation, "preparation_available": bool(preparation),
            "human_action_required": True,
            "reason": "A person must request, approve, and apply this operation outside Ricky's served tools.",
        })
    body = {"catalog_version": CATALOG_VERSION, "tools": tools, "operations": operations}
    return {**body, "catalog_hash": hash_json(body), "scope": "read_draft", "receipt_catalog_hash": CATALOG_HASH}


def _presentation(receipt: dict[str, Any]) -> dict[str, Any]:
    """Copy the receipt into a view; never rewrite bound facts or recorded text."""
    view = copy.deepcopy(receipt)
    view["receipt_provenance"] = {name: view.pop(name) for name in ("receipt_hash", "catalog_hash")}
    view["receipt_provenance"]["id"] = receipt["id"]
    view.pop("prev_hash")
    view["presentation"] = {"version": CATALOG_VERSION, "catalog_hash": catalog()["catalog_hash"], "raw_receipt": False}
    result = view.get("result")
    if isinstance(result, dict):
        # next_step is generated by draft handlers. Leave reasons, documents,
        # manifests, and read-model data intact even when they name SDK tools.
        step = result.get("next_step")
        if (CATALOG_BY_NAME[receipt["tool"]].side_effects == "draft" and isinstance(step, dict)
                and step.get("tool") in ("request_approval", "execute_approved_action")):
            step.pop("tool")
            step["human_action_required"] = True
            step["action"] = "review_approval"
            step["note"] = ("Only the named signer can approve this signature. A person must apply it in the contract workflow."
                            if step.get("operation") == "contract.sign" else
                            "Open the approval page. A person must request, approve, and apply this operation in its workflow.")
        if receipt["tool"] == "preview":
            result["note"] = "Preview only. A person must request, approve, and apply this operation in its workflow."
    if receipt["tool"] == "compute_invoice_match" and isinstance(view.get("error"), str):
        # This exact clause is generated for a still-holding match approval.
        # Avoid a general text substitution that could alter recorded data.
        view["error"] = view["error"].replace("run it with execute_approved_action", "have a person apply it in its workflow")
    return view


class ServedRicky:
    def __init__(self, sdk: RickySDK):
        self.sdk = sdk

    @staticmethod
    def catalog() -> dict[str, Any]:
        return catalog()

    def invoke(self, tool_name: Any, args: Any, *, actor: str, actor_role: str,
               idempotency_key: str | None = None) -> dict[str, Any]:
        # Refuse before SDK validation, receipt replay, or a handler can run.
        if not isinstance(tool_name, str) or tool_name not in SERVED_TOOLS:
            messages = {
                "execute_approved_action": "Only a person can apply this approval. Open its workflow to post, release, send, sign, or close.",
                "request_approval": "Only a person can request an approval. Open the approval page.",
                "reconcile_payments": "Only a person can reconcile payments. Open Payments.",
            }
            raise ServedRickyRefused(messages.get(tool_name, "Ricky serves read and draft tools only.")
                                     if isinstance(tool_name, str) else "Ricky serves read and draft tools only.")
        receipt = self.sdk.invoke(tool_name, args, actor=actor, actor_role=actor_role, idempotency_key=idempotency_key)
        return _presentation(receipt)
